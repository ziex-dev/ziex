const std = @import("std");

// mcp <kind> (<version> <schema.json>)... with the newest version first.
pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 4 or (args.len - 2) % 2 != 0) return error.Usage;

    const kind = args[1];
    var specs: std.ArrayListUnmanaged(Spec) = .empty;
    var i: usize = 2;
    while (i < args.len) : (i += 2) {
        const raw = try std.Io.Dir.cwd().readFileAlloc(io, args[i + 1], arena, .unlimited);
        const parsed = try std.json.parseFromSliceLeaky(std.json.Value, arena, raw, .{ .allocate = .alloc_always });
        if (parsed != .object) return error.InvalidSchema;
        const defs = parsed.object.get("$defs") orelse return error.MissingDefs;
        if (defs != .object) return error.InvalidDefs;
        try specs.append(arena, .{ .version = args[i], .defs = defs.object });
    }

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("// Generated by `zig build gen -- mcp`. Do not edit.\n\n");

    if (std.mem.eql(u8, kind, "version")) {
        try emitVersion(w, specs.items);
    } else if (std.mem.eql(u8, kind, "methods")) {
        try emitMethods(arena, w, specs.items);
    } else if (std.mem.eql(u8, kind, "error_codes")) {
        try emitErrorCodes(w);
    } else if (std.mem.eql(u8, kind, "defs_index")) {
        try emitDefsIndex(arena, w, specs.items);
    } else return error.Usage;

    var buf: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(io, &buf);
    try stdout.interface.writeAll(out.written());
    try stdout.interface.flush();
}

const Spec = struct {
    version: []const u8,
    defs: std.json.ObjectMap,

    // Legacy revisions open with an `initialize` handshake; modern ones are stateless.
    fn isLegacy(spec: Spec) bool {
        var it = spec.defs.iterator();
        while (it.next()) |entry| {
            const method = findMethodConst(entry.value_ptr.*) orelse continue;
            if (std.mem.eql(u8, method, "initialize")) return true;
        }
        return false;
    }
};

fn emitVersion(w: *std.Io.Writer, specs: []const Spec) !void {
    try w.writeAll("// Newest first.\npub const supported = ");
    try writeVersions(w, specs, null);
    try w.writeAll("\n// Stateless revisions: version and capabilities ride on every request's `_meta`.\npub const modern = ");
    try writeVersions(w, specs, false);
    try w.writeAll("\n// Revisions that open with an `initialize` handshake.\npub const legacy = ");
    try writeVersions(w, specs, true);
    try w.writeAll("\npub const protocol_version = supported[0];\n");
}

// `zig fmt` style: padded braces only around more than one element.
fn writeVersions(w: *std.Io.Writer, specs: []const Spec, legacy: ?bool) !void {
    var count: usize = 0;
    for (specs) |spec| {
        if (legacy == null or legacy.? == spec.isLegacy()) count += 1;
    }
    try w.writeAll("[_][]const u8{");
    if (count > 1) try w.writeByte(' ');
    var i: usize = 0;
    for (specs) |spec| {
        if (legacy != null and legacy.? != spec.isLegacy()) continue;
        if (i > 0) try w.writeAll(", ");
        try w.print("\"{s}\"", .{spec.version});
        i += 1;
    }
    if (count > 1) try w.writeByte(' ');
    try w.writeAll("};\n");
}

fn emitErrorCodes(w: *std.Io.Writer) !void {
    try w.writeAll(
        \\pub const parse_error: i64 = -32700;
        \\pub const invalid_request: i64 = -32600;
        \\pub const method_not_found: i64 = -32601;
        \\pub const invalid_params: i64 = -32602;
        \\pub const internal_error: i64 = -32603;
        \\pub const header_mismatch: i64 = -32020;
        \\pub const missing_required_client_capability: i64 = -32021;
        \\pub const unsupported_protocol_version: i64 = -32022;
        \\
    );
}

const MethodEntry = struct {
    wire: []const u8,
    tag: []const u8,
    def_name: []const u8,
};

// Every method of every given revision.
fn emitMethods(arena: std.mem.Allocator, w: *std.Io.Writer, specs: []const Spec) !void {
    var list: std.ArrayListUnmanaged(MethodEntry) = .empty;
    for (specs) |spec| {
        var it = spec.defs.iterator();
        next: while (it.next()) |entry| {
            const def_name = entry.key_ptr.*;
            const is_req = std.mem.endsWith(u8, def_name, "Request");
            const is_notif = std.mem.endsWith(u8, def_name, "Notification");
            if (!is_req and !is_notif) continue;
            const method = findMethodConst(entry.value_ptr.*) orelse continue;
            for (list.items) |m| if (std.mem.eql(u8, m.wire, method)) continue :next;
            const tag = try wireToTag(arena, method);
            try list.append(arena, .{ .wire = method, .tag = tag, .def_name = def_name });
        }
    }

    std.mem.sort(MethodEntry, list.items, {}, struct {
        fn less(_: void, a: MethodEntry, b: MethodEntry) bool {
            return std.mem.order(u8, a.wire, b.wire) == .lt;
        }
    }.less);

    try w.writeAll(
        \\pub const Method = enum {
        \\
    );
    for (list.items) |m| {
        try w.print("    {s},\n", .{m.tag});
    }
    try w.writeAll(
        \\
        \\    pub fn toString(self: Method) []const u8 {
        \\        return switch (self) {
        \\
    );
    for (list.items) |m| {
        try w.print("            .{s} => \"{s}\",\n", .{ m.tag, m.wire });
    }
    try w.writeAll(
        \\        };
        \\    }
        \\
        \\    pub fn fromString(s: []const u8) ?Method {
        \\        inline for (@typeInfo(Method).@"enum".field_names, @typeInfo(Method).@"enum".field_values) |_, value| {
        \\            const m: Method = @fromBackingInt(@intCast(value));
        \\            if (std.mem.eql(u8, m.toString(), s)) return m;
        \\        }
        \\        return null;
        \\    }
        \\};
        \\
        \\const std = @import("std");
        \\
        \\pub fn defName(method: Method) []const u8 {
        \\    return switch (method) {
        \\
    );
    for (list.items) |m| {
        try w.print("        .{s} => \"{s}\",\n", .{ m.tag, m.def_name });
    }
    try w.writeAll(
        \\    };
        \\}
        \\
    );
}

fn emitDefsIndex(arena: std.mem.Allocator, w: *std.Io.Writer, specs: []const Spec) !void {
    var names: std.ArrayListUnmanaged([]const u8) = .empty;
    for (specs) |spec| {
        var it = spec.defs.iterator();
        next: while (it.next()) |entry| {
            for (names.items) |n| if (std.mem.eql(u8, n, entry.key_ptr.*)) continue :next;
            try names.append(arena, entry.key_ptr.*);
        }
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn less(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.less);

    try w.writeAll(
        \\pub const defs = [_][]const u8{
        \\
    );
    for (names.items) |n| {
        try w.print("    \"{s}\",\n", .{n});
    }
    try w.writeAll("};\n");
}

fn findMethodConst(value: std.json.Value) ?[]const u8 {
    if (value != .object) return null;
    if (value.object.get("properties")) |props| {
        if (props == .object) {
            if (props.object.get("method")) |m| {
                if (m == .object) {
                    if (m.object.get("const")) |c| {
                        if (c == .string) return c.string;
                    }
                }
            }
        }
    }
    if (value.object.get("allOf")) |all_of| {
        if (all_of == .array) {
            for (all_of.array.items) |part| {
                if (findMethodConst(part)) |m| return m;
            }
        }
    }
    return null;
}

fn wireToTag(arena: std.mem.Allocator, wire: []const u8) ![]const u8 {
    var out: std.ArrayListUnmanaged(u8) = .empty;
    for (wire) |c| {
        if (c == '/' or c == '-') {
            try out.append(arena, '_');
        } else {
            try out.append(arena, c);
        }
    }
    return out.items;
}
